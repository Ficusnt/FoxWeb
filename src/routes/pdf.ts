import type { Hono } from "hono";
import type { PDFParams, CoefficientTable } from "../types/index";
import { getTable } from "../lib/storage";

export const pdfRoute = (env: Env, c: Hono<Hono.Context>) => {
  // Generate PDF for a specific table
  pdf.get("/:tableId", async (c) => {
    const tableId = c.req.param("tableId");
    const table = await getTable(c.env.TABLES_KV, tableId);

    if (!table) {
      return c.json({ error: "Table not found" }, 404);
    }

    // Generate PDF content from table data
    const pdfContent = generatePdfContent(table);

    const fileName = `${table.name || tableId}.pdf`;

    return c.body(pdfContent, {
      headers: {
        "Content-Disposition": `attachment; filename="${fileName}"`,
        "Content-Type": "application/pdf",
      },
    });
  });

  // Generate PDF with parameters
  pdf.post("/generate", async (c) => {
    const params = await c.req.json<PDFParams>();

    // Validate required parameters
    if (!params.tableId || !params.tableName) {
      return c.json({ error: "Missing tableId or tableName" }, 400);
    }

    const table = await getTable(c.env.TABLES_KV, params.tableId);

    if (!table) {
      return c.json({ error: "Table not found" }, 404);
    }

    const pdfContent = generatePdfContent(table, params);

    return c.body(pdfContent, {
      headers: {
        "Content-Disposition": `attachment; filename="${params.tableName}.pdf"`,
        "Content-Type": "application/pdf",
      },
    });
  });

  return pdf;
};

/**
 * Generate PDF content from a CoefficientTable
 * This is a placeholder - integrate with actual PDF generation library
 */
function generatePdfContent(
  table: CoefficientTable,
  params?: PDFParams
): ArrayBuffer {
  // TODO: Integrate with PDF generation library (pdfkit, jsPDF, etc.)
  // For now, return a minimal ArrayBuffer with PDF header
  const pdfHeader = "%PDF-1.4\n%Generated by FoxWeb\n";
  const minimalBody =
    "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n";
  const pagesObj =
    "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n";
  const resourcesObj =
    "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] >>\nendobj\n";
  const contentObj =
    "4 0 obj\n<< /Length 44 >>\nstream\nBT /F1 24 Tf 100 700 Td (Hello FoxWeb) Tj ET\nendstream\nendobj\n";

  const parts = [
    Buffer.from(pdfHeader),
    Buffer.from(minimalBody),
    Buffer.from(pagesObj),
    Buffer.from(resourcesObj),
    Buffer.from(contentObj),
  ];

  return Buffer.concat(parts).buffer;
}